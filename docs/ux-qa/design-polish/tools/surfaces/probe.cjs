const L = require('./lib.cjs');
const path = require('path');
(async () => {
	const browser = await L.launchBrowser();
	const vp = process.argv[2] || 'desktop';
	const ctx = await L.newContext(browser, vp);
	const errors = [];
	const page = await L.newPage(ctx, errors);
	const cdp = await ctx.newCDPSession(page);
	await cdp.send('DOM.enable'); await cdp.send('CSS.enable');
	let t = Date.now();
	await page.goto(L.BASE + '/');
	await page.locator('[data-testid="home-page"]').waitFor({ timeout: 30000 });
	console.log('home', Date.now() - t);
	await L.settle(page);
	const m = await page.evaluate(L.collectInPage, { touch: false });
	console.log(JSON.stringify(m.counts), m.elements.slice(0, 3));
	t = Date.now();
	await page.goto(L.BASE + '/game/future-lost');
	await page.locator('[data-testid="screen-showIntro"]').waitFor({ timeout: 30000 });
	console.log('intro', Date.now() - t);
	await L.settle(page);
	await page.screenshot({ path: path.join(__dirname, 'probe', vp + '-intro.png') });
	console.log(await L.store(page, `return { s: gs.gameState.state, deck: gs.gameState.deck.length, d: gs.gameState.config.options, labels: Object.keys(gs.gameState.config.labels||{}) }`));
	// force a card
	t = Date.now();
	await L.store(page, `const g = gs.gameState; g.state = 'rollForTasks';`);
	await page.waitForTimeout(800);
	await L.store(page, `const g = gs.gameState; const i = g.deck.findIndex(c => c.card === '7'); const [c] = g.deck.splice(i,1); g.deck.push(c); g.cardsToDraw = 2; g.state = 'drawCard';`);
	await page.locator('.byte-container.revealed, [data-testid="card"]').first().waitFor({ timeout: 15000 }).catch(e => console.log('no card', e.message.split('\n')[0]));
	console.log('card', Date.now() - t);
	await L.settle(page);
	console.log('settled', Date.now() - t);
	await page.screenshot({ path: path.join(__dirname, 'probe', vp + '-card.png') });
	console.log(await page.evaluate(() => document.querySelector('[data-testid="card"]')?.className));
	console.log(errors.slice(0, 10));
	await browser.close();
})();
